/*
 * みずほ注文締の約定一覧。`GET /executions?route=0` の実 API と同じ形
 * （docs/api/openapi.json の ExecutionItem。キーは日本語・生の形のまま）。
 *
 * 12 件はすべて注文ルート 0（みずほ）で、並びは約定日時の新しい順（実 API の既定 desc）。
 * 内訳は 買 7 件 / 売 5 件、全部出来 8 件 / 一部出来 2 件 / 取消済（出来有）2 件。
 * 取消済の 2 件は 032 と 034 を 1 件ずつ持つ（画面はどちらも「取消済（出来有）」に寄せる）。
 *
 * 約定照会（`/executions`）のフィクスチャができたら、そちらの みずほ の行へ寄せて畳む
 * （src/api/mizuhoExecutions.js の冒頭コメント）。
 */

const SIDE_NAMES = { 3: '買', 1: '売' }
const STATUS_NAMES = { '011': '全部出来', '010': '一部出来', '032': '取消済', '034': '取消済' }

/** 約定代金_JPY（円貨の概算）に使う USD/JPY。実 API は直近の USD レートを掛ける */
export const MIZUHO_EXECUTION_FX_RATE = 150

/**
 * 1 行ぶんの ExecutionItem。画面ごとに違う値だけを受け取り、みずほの行で共通の値
 * （注文ルート・決済通貨・IB 側の ID が無いこと）はここで埋める。
 */
function execution({
  id,
  orderId,
  branchCode,
  branchName,
  accountNo,
  customerName,
  symbol,
  symbolName,
  side,
  status,
  quantity,
  limitPrice,
  executedQuantity,
  executedPrice,
  executedAt,
}) {
  const amount = Math.round(executedQuantity * executedPrice * 100) / 100

  return {
    ID: id,
    注文ID: orderId,
    受注番号: `${branchCode}-${String(orderId).padStart(6, '0')}`,
    伝票注文ID: null,
    伝票受注番号: null,
    部店: branchCode,
    部店名: branchName,
    口座番号: accountNo,
    顧客名: customerName,
    銘柄コード: symbol,
    Ticker: symbol,
    銘柄名: symbolName,
    売買区分: side,
    売買区分名: SIDE_NAMES[side],
    注文ルート: '0',
    注文ルート名: 'みずほ',
    処理状況: status,
    処理状況名: STATUS_NAMES[status],
    注文数量: quantity,
    指値単価: limitPrice,
    // みずほ経由の約定は IB の注文 ID / 約定 ID を持たない
    OrderID: null,
    ExecID: null,
    約定数量: executedQuantity,
    約定単価: executedPrice,
    約定代金: amount,
    約定代金_JPY: Math.round(amount * MIZUHO_EXECUTION_FX_RATE),
    約定日時: executedAt,
    決済通貨区分: '0',
    手数料: null,
    手数料通貨: null,
    作成日時: executedAt,
  }
}

